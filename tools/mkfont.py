# Pre-rasterises Poppins (SIL Open Font License) into 8-bit alpha glyph tables.
import os
from PIL import Image, ImageDraw, ImageFont
G='/usr/share/fonts/truetype/google-fonts/'
FONTS=[('F_SMALL','Poppins-Medium.ttf',14),('F_BODY','Poppins-Medium.ttf',17),('F_BODYB','Poppins-Bold.ttf',17),
       ('F_BTN','Poppins-Bold.ttf',20),('F_TITLE','Poppins-Bold.ttf',27),('F_BIG','Poppins-Bold.ttf',42)]
out=['/* generated by tools/mkfont.py from Poppins (SIL OFL 1.1) */','#include "font.h"']
names=[]
for name,file,size in FONTS:
    f=ImageFont.truetype(G+file,size)
    asc,desc=f.getmetrics()
    glyphs=[];data=[]
    for c in range(32,127):
        ch=chr(c)
        adv=round(f.getlength(ch))
        bbox=f.getbbox(ch)  # relative to origin at top of ascent
        if bbox[2]<=bbox[0] or bbox[3]<=bbox[1]:
            glyphs.append((adv,0,0,0,0,len(data)));continue
        x0,y0,x1,y1=bbox
        w,h=x1-x0,y1-y0
        im=Image.new('L',(w,h),0);d=ImageDraw.Draw(im);d.text((-x0,-y0),ch,font=f,fill=255)
        glyphs.append((adv,x0,y0,w,h,len(data)))
        data.extend(im.tobytes())
    out.append('static const unsigned char %s_px[%d]={%s};'%(name,max(1,len(data)),','.join(map(str,data)) or '0'))
    out.append('static const Glyph %s_g[95]={%s};'%(name,','.join('{%d,%d,%d,%d,%d,%d}'%g for g in glyphs)))
    out.append('const Font %s_font={%d,%d,%s_g,%s_px};'%(name,asc+desc,asc,name,name))
    names.append(name)
open(os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','source','font_data.c'),'w').write('\n'.join(out)+'\n')
print('ok',names)
